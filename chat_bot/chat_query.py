def group_threads_output(response, threads_output, tables):
    
    
    # First get the ordered tables
    ordered_tables = [table['table_name'] for table in tables]
    # Reorder the output by how they were given in the input aka sorted by relevance. Not by time it took for completion
    # Sorting output_threads based on whether the table name contains any string in the tables list
    output_threads_sorted = sorted(threads_output, key=lambda x: find_table_index(x["Table Name"],ordered_tables))

        
    response['Tables Queried'] = ordered_tables
    
    try:
        # Initialize collections

        print(response['Performance Data'])


        # Ensure the nested structure exists
        if 'run_chat_query' not in response['Performance Data']['run_chat_bot_time']:
            response['Performance Data']['run_chat_bot_time']['run_chat_query'] = {}

        

        generated_queries = []
        sql_queries = []
        tokens_used = []
        thread_performances = {}

        # Process each thread's output in a single loop
        for num, thread in enumerate(threads_output):
            generated_queries.append(thread['Generated Query'])
            sql_queries.append(thread['SQL Query'][0])
            tokens_used.append(thread['Tokens Used'])
            thread_performances[f'thread {num}'] = thread['Performance Data']

        # Assign aggregated data to the response dictionary
        response['Generated Query'] = generated_queries
        response['SQL Query'] = sql_queries
        response['Tokens Used']['chat_query_threads'] = tokens_used
        response['Performance Data']['run_chat_bot_time']['run_chat_query']['Threads'] = thread_performances

    except KeyError as e:
        trace = traceback.format_exc()
        print(trace)
        print(f"Key error: {e} - One of the expected keys is missing in thread output.")
    except IndexError as e:
        print(f"Index error: {e} - Attempted to access a non-existent index.")
    return response


def query_gen_parallel(response, tables):
    
    # Create dictionary for each table to run in threads
    parallel_tables = {}
    for table in tables:
        parallel_tables[table['table_name']] = table['content']
        
    # List of run_chat_query_parallel functions with arguments respective arguments
    functions_to_run = []
    for table_schema in parallel_tables.items():
        # Each entry is a tuple (function, args_tuple, kwargs_dict)
        functions_to_run.append((run_chat_query_parallel, (response, table_schema), {}))
        
    # Run functions in threads
    threads_output = run_functions_in_threads(functions_to_run)
    
    
    response = group_threads_output(response, threads_output, tables)

    return response