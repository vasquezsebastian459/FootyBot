class QueryRunner:
    def __init__(self, chatbot: 'Chatbot'):
        self.chatbot = chatbot

        self.response = {}

    def prepare_response(self, response):

        self.response['User Question'] = self.chatbot.question
        self.response['Previous Context'] = self.chatbot.context
        self.response['Key Information Context'] = self.chatbot.key_info_extractor.augmented_key_info
        self.response['Performance Data'] = {
                "Overall Time": -1,
                "extract_key_info_time": {'Total Time' : -1},
                "get_user_intention_time": {'Total Time' : -1,
                                            'validate_run_query': -1},
                "run_chat_bot_time": {'Total Time' : -1},
                'run_chat_query': {}
            }
        
        self.response['Tokens Used'] = {
            'chat_query_threads': {}
        }


        return self.response


    # Helper function to handle the execution and validation of each query:
    @staticmethod
    def execute_query_task(query_info):
        total_time = time.time()
        sql_query, schema, num = query_info
        query_perf_data = {}
        query_perf_data['total_time'] = -1 # Placeholder for total time
        name = f'SQL Data {num}'
        
        # Validate the SQL query
        start_time = time.time()
        query_status = validate_sql_query(sql_query, schema)
        query_perf_data['validate_query_time'] = time.time() - start_time
        
        if query_status[0] == False:
            return name, query_status[1], query_perf_data
        else:
            # Add more info to the query
            start_time = time.time()
            sql_query = add_info_to_query(sql_query, schema)
            query_perf_data['add_info_to_query_time'] = time.time() - start_time

            if "remove_invalid_cols" in query_status[1]:
                sql_query = query_status[2]

            
            # Add a where clause excluding some player_id or team_id
            start_time = time.time()

            # Here we correct the query using sql.parse
            query_tokens = extract_sql_tokens(sql_query)
            # first, if we are selecting player_id or team_id. We add a where clause to exclude some ids
            corrected_query = modify_sql_query(sql_query,query_tokens )
            
            # Second, we add an is not null clause to the query for columns that are not ids
            corrected_query = is_not_null_sql_query(corrected_query, query_tokens)
            
            query_perf_data['openai_correct_query_time'] = time.time() - start_time

            # Get data from the database
            start_time = time.time()
            sql_data = get_db_data(corrected_query)
            query_perf_data['get_db_data'] = time.time() - start_time

            if sql_data[0] == "Database error" and len(sql_data) >= 3:
                start_time = time.time()
                error = sql_data[2]
                print("error", error)
                suggested_query = openai_correct_query(corrected_query, instructions=str(error))
                print("suggested_query", suggested_query)
                print_colored(f"Database error, suggested query: {suggested_query}", "BACKGROUND_RED")
                sql_data = get_db_data(suggested_query)
                query_perf_data['query_database_error'] = time.time() - start_time

            query_perf_data['total_time'] = time.time() - total_time
            return name, sql_data, query_perf_data


    def validate_run_query(self,queries, output, schema):
        """
        This function is to:
        - Validate the SQL queries generated by the chatbot.
        - If valid, run the query in the database and get the data.
        """
        
        # Ensure the performance structure is in place
        output['Performance Data']['run_chat_bot_time'].setdefault('validate_run_query', {'queries': {}})


        output['SQL Data'] = {}

        # Prepare the list of query information tuples
        query_info_list = [(query, schema, num) for num, query in enumerate(queries)]

        # Run queries in parallel
        with ThreadPoolExecutor(max_workers=10) as executor:
            futures = {executor.submit(self.execute_query_task, query_info): query_info for query_info in query_info_list}
            for future in futures:
                try:
                    name, sql_data, query_perf_data = future.result(timeout=10)  # wait max 15s
                    output['SQL Data'][name] = sql_data
                    output['Performance Data']['run_chat_bot_time']['validate_run_query']['queries'][name] = query_perf_data
                    print_colored_full_line("", "WHITE")
                except Exception as e:
                    print_colored(f"❌ Error during query execution: {str(e)}", "RED")
                    traceback.print_exc()

                    
        return output


    def rerun_checker(self, response):

        rerun = False
        # THis part here will look through the output of the sql and check if theres a need to rerun again with the table removed
        sql_data = response['SQL Data']
        total_queries = len(sql_data)
        counter = 0
        table_names = []

        for _, value in sql_data.items():
            if value[0] == "Database error":
                counter += 1
                table_names.append(value[1])

        if total_queries == counter:
            start_time = time.time()
            print_colored_full_line("", "BACKGROUND_RED")
            print_colored(f"All queries are invalid: RERUN", "BACKGROUND_RED")
            print_colored(f"ADD LOGIC TO HANDLE RERUN!", "BACKGROUND_RED")
            print_colored_full_line("", "BACKGROUND_RED")

            # Here we write the output to a file so we can check what were the queries generated that gave an error
            write_json(response, prefix = 'Re_Run', output_dir= 'chat_bot/temporary_logs') 
            response['Performance Data']['run_chat_bot_time']['Rerun'] = time.time() - start_time
            rerun = True
        
        return rerun
        
    def run(self, response, tables):

        response = self.prepare_response(response)

        response = query_gen_parallel(response,tables) 

        sql_queries = response['SQL Query']


        response = self.validate_run_query(sql_queries, response, self.chatbot.all_tables2col)

        print(response)

        # Check if we need to rerun
        rerun = self.rerun_checker(response)

        print(f"RERUN: {rerun}")
        
        return response
